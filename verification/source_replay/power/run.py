"""Repeat the supplement's planted-effect experiment on the reconstructed primary drug panel."""
import argparse
import os
from pathlib import Path
import subprocess
import sys

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work", type=Path, required=True, help="Same work directory as the completed Part B analysis")
    parser.add_argument("--workers", type=int, default=4)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--summarize-saved", action="store_true",
                      help="Reuse the completed assignment records already in <work>/power/raw; rerun diagnostics and summaries")
    mode.add_argument("--harness-only", action="store_true", help="Check the inputs and calibration before simulation")
    args = parser.parse_args()
    work = args.work.resolve()
    if not 1 <= args.workers <= 8 or work.is_relative_to(HERE.parents[2]):
        parser.error("Use 1–8 workers for the power simulation and a work directory outside the checkout.")
    if not (work / "results/G/G_calibration.tsv").is_file():
        parser.error("Run the Part B model first. Its calibration and fitted design are required.")
    out = work / "power"
    for name in ("raw", "results", "logs"):
        (out / name).mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "PYTHONHASHSEED": "0", "P59_LINCS_WORK": str(work)}
    jobs = [("check_harness",)]
    if not args.harness_only:
        if args.summarize_saved:
            for file in ("power_runs.tsv.gz", "power_planted.tsv.gz", "power_e2.npz"):
                if not (out / "raw" / file).is_file():
                    parser.error(f"Missing saved assignments: {out / 'raw' / file}")
            print("Using saved assignments; recalculating summaries and calibration diagnostics.", flush=True)
        else:
            jobs.append(("power_checkpoint", "--B", "2000", "--R", "1000", "--workers", str(args.workers), "--tag", "power"))
        jobs += [("summarize_power", "--tag", "power"), ("size_from_calibration",),
                 ("size_diagnostic", "--N", "200", "--B", "2000", "--workers", str(args.workers)),
                 ("tp53_yardstick",), ("misclass_e3",), ("e3_table",), ("e3_weak_templates",), ("detectable_effects",)]
    for script, *extra in jobs:
        subprocess.run([sys.executable, "-B", str(HERE / "scripts" / (script + ".py")), *extra],
                       env=env, cwd=out, check=True)
    if not args.harness_only:
        import pandas as pd
        for reference in (HERE / "full_run").glob("*.tsv"):
            if reference.name == "figure_denominators.tsv":
                continue  # This file is generated by the separate assignment audit.
            actual = pd.read_csv(out / "results" / reference.name, sep="\t")
            expected = pd.read_csv(reference, sep="\t")
            if reference.name == "size_panel_test.tsv":
                calibration = Path(actual.pop("source_file").unique().item())
                if calibration.resolve() != (work / "results/G/G_calibration.tsv").resolve():
                    raise ValueError("Calibration was read from an unexpected file")
            pd.testing.assert_frame_equal(actual, expected, check_exact=False, atol=1e-12, rtol=1e-12)
        print("Checked the regenerated power, interval coverage, calibration and Figure S3 tables.")


if __name__ == "__main__":
    main()
